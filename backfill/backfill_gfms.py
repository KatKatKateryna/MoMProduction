"""
backfill_gfms.py -- regenerate missing GFMS image (tiff) products, and the
matching per-watershed summary CSVs, for historical dates.

Scope is deliberately narrow: GFMS image + GFMS summary only. It does not
touch GloFAS, HWRF, DFO, VIIRS, the Final_Alert composite, or the database.

Why this exists: image products were never generated under cron (gdal_translate
was unresolvable without an activated conda env), so GFMS_image/ is empty while
GFMS_summary/ is fully populated. GFMS_processing() only calls the extractor
when the summary CSV is absent, so the normal job will never regenerate these.

Each run walks forward from --start, finds the earliest day not yet done in
this pass, and processes at most --max-days such days. A day is done once its
marker is written to GFMS_backfill_state/, so existing images and summaries
inside the range are regenerated and overwritten, oldest day first (each day's
durations build on the previous day's recomputed 21z summary).
--end caps the range: nothing after it is ever looked at. Dates that are not
yet settled are excluded regardless of --end.

Usage:
    python backfill/backfill_gfms.py                        # 20260101 .. 20261013
    python backfill/backfill_gfms.py --start 20260101 --end 20261013 --max-days 220
"""

import argparse
import glob
import os
import sys
import time
from datetime import datetime, timedelta, timezone

import requests

# the project modules are one folder up
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import settings  # noqa: E402
from GFMS_tool import GFMS_data_extractor, GFMS_fix_duration

BINHOURS = ["00", "03", "06", "09", "12", "15", "18", "21"]

# current backfill pass (inclusive)
DEFAULT_START = "20260101"
DEFAULT_END = "20261013"

# days with no data at the source are marked here so later runs skip them
# instead of stalling on the same gap forever
STATE_DIR = os.path.join(settings.GFMS_DIR, "GFMS_backfill_state")

def log(msg):
    """timestamped line, flushed so `tail -f` on the cron log stays live"""
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    print(f"[{stamp}] {msg}", flush=True)


def tiff_path(real_date, binhour):
    return os.path.join(
        settings.GFMS_IMG_DIR, f"Flood_byStor_{real_date}{binhour}.tiff"
    )


def day_is_done(real_date):
    """images and summaries of this day regenerated by the backfill"""
    return os.path.exists(os.path.join(STATE_DIR, f"{real_date}.done"))


def mark_done(real_date, images):
    os.makedirs(STATE_DIR, exist_ok=True)
    with open(os.path.join(STATE_DIR, f"{real_date}.done"), "w") as f:
        f.write(f"{datetime.now(timezone.utc).isoformat()} images={images}/8\n")


def day_is_skipped(real_date):
    return os.path.exists(os.path.join(STATE_DIR, f"{real_date}.nodata"))


def mark_skipped(real_date, reason):
    os.makedirs(STATE_DIR, exist_ok=True)
    with open(os.path.join(STATE_DIR, f"{real_date}.nodata"), "w") as f:
        f.write(f"{datetime.now(timezone.utc).isoformat()} {reason}\n")


def missing_at_source(bin_file):
    """True only when the source answers that the file does not exist; a
    failed download of an existing file is an error to retry"""
    datestr = bin_file.split("_")[2]
    baseurl = settings.config.get("gfms", "HOST").rstrip("/")
    url = f"{baseurl}/{datestr[:4]}/{datestr[:6]}/{bin_file}"
    try:
        return requests.head(url, allow_redirects=True, timeout=60).status_code == 404
    except requests.exceptions.RequestException:
        return False


def cleanup_proc_files(real_date):
    """remove the day's .bin/.hdr/.vrt/.csv from the processing folder

    GFMS_processing() archives and deletes these after a normal run, but the
    backfill bypasses it, so without this every backfilled day left ~60MB of
    raw downloads behind. Summaries are already in GFMS_summary/ by now and
    the .bin files can be re-downloaded if a day ever needs redoing.
    """
    files = glob.glob(
        os.path.join(settings.GFMS_PROC_DIR, f"Flood_byStor_{real_date}*.*")
    )
    for f in files:
        try:
            os.remove(f)
        except OSError as exc:
            log(f"  could not delete {f}: {exc}")
    return len(files)


def find_days_to_process(start_date, end_date, max_days):
    """earliest-first list of days not yet done, within the range"""
    # the source publishes forecasts ahead of time, but only backfill dates
    # that are safely complete; --end caps that, it does not extend it
    settled = datetime.now(timezone.utc).replace(
        hour=0, minute=0, second=0, microsecond=0
    ) - timedelta(days=1)
    last_date = min(end_date, settled)

    days = []
    cursor = start_date
    while cursor <= last_date and len(days) < max_days:
        real_date = cursor.strftime("%Y%m%d")
        if not day_is_done(real_date) and not day_is_skipped(real_date):
            days.append(cursor)
        cursor += timedelta(days=1)
    return days


def process_day(day):
    """regenerate images + summaries for one day; returns per-file timings"""
    real_date = day.strftime("%Y%m%d")
    day_start = time.monotonic()
    log(f"DAY {real_date} start")

    produced = []
    timings = []
    errors = 0

    for binhour in BINHOURS:
        bin_file = f"Flood_byStor_{real_date}{binhour}.bin"
        proc_csv = os.path.join(
            settings.GFMS_PROC_DIR, bin_file.replace(".bin", ".csv")
        )
        # force recomputation: extract_by_watershed returns early if this exists
        if os.path.exists(proc_csv):
            os.remove(proc_csv)

        t0 = time.monotonic()
        started = time.time()
        try:
            GFMS_data_extractor(bin_file)
        except Exception as exc:
            log(f"  {bin_file} FAILED: {exc}")
            errors += 1
            continue
        elapsed = time.monotonic() - t0

        # an existing image is overwritten in place; only a fresh one counts
        tiff = tiff_path(real_date, binhour)
        made_tiff = os.path.exists(tiff) and os.path.getmtime(tiff) >= started - 1
        if made_tiff:
            produced.append(binhour)
            timings.append(elapsed)
            log(f"  {real_date}{binhour} ok {elapsed:6.1f}s")
        elif missing_at_source(bin_file):
            log(f"  {real_date}{binhour} no data at source {elapsed:6.1f}s")
        else:
            log(f"  {real_date}{binhour} FAILED: no image produced {elapsed:6.1f}s")
            errors += 1

    if errors:
        # e.g. disk full or download errors: leave the day for the next run
        # instead of marking it as having no data
        cleanup_proc_files(real_date)
        log(f"DAY {real_date} {errors} error(s) - retried next run")
        return None

    if not produced:
        mark_skipped(real_date, "no images produced")
        cleanup_proc_files(real_date)
        log(f"DAY {real_date} no data at source - marked skipped")
        return timings

    # recompute summaries, overwriting any existing file for these dates
    csvlist = [
        f"Flood_byStor_{real_date}{h}.csv"
        for h in BINHOURS
        if os.path.exists(
            os.path.join(settings.GFMS_PROC_DIR, f"Flood_byStor_{real_date}{h}.csv")
        )
    ]
    prev_day = (day - timedelta(days=1)).strftime("%Y%m%d")
    base0 = f"Flood_byStor_{prev_day}21.csv"
    try:
        GFMS_fix_duration(base0, csvlist)
    except Exception as exc:
        log(f"  summary fix FAILED for {real_date}: {exc}")

    removed = cleanup_proc_files(real_date)
    log(f"  removed {removed} processing file(s)")
    mark_done(real_date, len(produced))

    total = time.monotonic() - day_start
    per_file = (sum(timings) / len(timings)) if timings else 0.0
    log(
        f"DAY {real_date} done {total:7.1f}s  "
        f"images={len(produced)}/8  avg/file={per_file:5.1f}s  "
        f"summaries={len(csvlist)}"
    )
    return timings


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--start", default=DEFAULT_START, help="earliest date to backfill, YYYYMMDD"
    )
    parser.add_argument(
        "--end", default=DEFAULT_END, help="last date to backfill (inclusive), YYYYMMDD"
    )
    parser.add_argument(
        "--max-days", type=int, default=220, help="maximum days per run"
    )
    args = parser.parse_args()

    start_date = datetime.strptime(args.start, "%Y%m%d").replace(tzinfo=timezone.utc)
    end_date = datetime.strptime(args.end, "%Y%m%d").replace(tzinfo=timezone.utc)
    if end_date < start_date:
        log(f"end {args.end} is before start {args.start} - nothing to do")
        return 0

    os.makedirs(settings.GFMS_IMG_DIR, exist_ok=True)
    os.makedirs(STATE_DIR, exist_ok=True)

    run_start = time.monotonic()
    log(
        f"backfill start: {args.start}..{args.end}, max {args.max_days} days/run"
    )

    days = find_days_to_process(start_date, end_date, args.max_days)
    if not days:
        log("nothing to backfill - all days complete")
        return 0

    log(
        f"selected {len(days)} day(s): "
        f"{days[0].strftime('%Y%m%d')} .. {days[-1].strftime('%Y%m%d')}"
    )

    all_timings = []
    for day in days:
        timings = process_day(day)
        if timings is None:
            # later days build on this one's summaries, so stop here
            break
        all_timings.extend(timings)

    total = time.monotonic() - run_start
    n = len(all_timings)
    log(
        f"RUN done {total:7.1f}s  days={len(days)}  images={n}  "
        f"avg/file={(sum(all_timings) / n if n else 0):5.1f}s  "
        f"avg/day={(total / len(days)):6.1f}s"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
